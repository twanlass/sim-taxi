"""
Bakes the startup screen logo's letters (game/splashlogo.js) out of the game's own Space Grotesk:
the shipped woff2 instanced at weight 700, each glyph's outline flattened into polylines in units of
cap height, written to src/game/logoglyphs.js. Every mesh in the game is generated in code from data,
so the font file is read here, once, rather than loaded at runtime.

    python3 -m pip install fonttools brotli
    python3 tools/logo-glyphs.py

Curves are flattened to a fixed few segments each (`QUAD_STEPS`), which is the low-poly part: at the
splash's size a bowl drawn in three facets per quadratic reads as the font, and the facets catch the
light the way every other surface in the city does.
"""
import json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.basePen import BasePen

SRC = 'assets/fonts/SpaceGrotesk-latin.woff2'
OUT = 'src/game/logoglyphs.js'
LETTERS = 'ROCKETIDS'
WEIGHT = 700
QUAD_STEPS = 3


class Flatten(BasePen):
    def __init__(self, glyphset):
        super().__init__(glyphset)
        self.contours = []
        self.cur = None

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]
        for k in range(1, QUAD_STEPS + 1):
            t = k / QUAD_STEPS
            a, b, c = (1 - t) ** 2, 2 * (1 - t) * t, t * t
            self.cur.append((a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]))

    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]
        for k in range(1, QUAD_STEPS + 2):
            t = k / (QUAD_STEPS + 1)
            a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
            self.cur.append(tuple(a * p0[i] + b * p1[i] + c * p2[i] + d * p3[i] for i in (0, 1)))

    def _closePath(self):
        if len(self.cur) > 1 and self.cur[0] == self.cur[-1]:
            self.cur.pop()
        self.contours.append(self.cur)
        self.cur = None

    _endPath = _closePath


font = instantiateVariableFont(TTFont(SRC), {'wght': WEIGHT})
cap = font['OS/2'].sCapHeight
cmap = font.getBestCmap()
glyphset = font.getGlyphSet()
glyphs = {}
for ch in LETTERS:
    name = cmap[ord(ch)]
    pen = Flatten(glyphset)
    glyphset[name].draw(pen)
    lsb = font['hmtx'][name][1]
    adv = font['hmtx'][name][0]
    # Measured from the outline's own left edge: the logo is set with its own tracking.
    xs = [x for c in pen.contours for x, _ in c]
    x0, x1 = min(xs), max(xs)
    glyphs[ch] = {
        'w': round((x1 - x0) / cap, 4),
        'contours': [[[round((x - x0) / cap, 4), round(y / cap, 4)] for x, y in c] for c in pen.contours],
    }

with open(OUT, 'w') as f:
    f.write('// Generated by tools/logo-glyphs.py from assets/fonts/SpaceGrotesk-latin.woff2 at weight '
            f'{WEIGHT}. Do not edit.\n')
    f.write('// Each glyph: its inked width and its outlines, flattened, in units of cap height.\n')
    f.write('export const LOGO_GLYPHS = ')
    f.write(json.dumps(glyphs, separators=(',', ':')))
    f.write(';\n')
print({k: (v['w'], len(v['contours']), sum(len(c) for c in v['contours'])) for k, v in glyphs.items()})
